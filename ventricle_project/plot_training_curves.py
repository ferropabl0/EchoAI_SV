import argparse
from pathlib import Path

import matplotlib

#Backend that works without graphical display
#Do before importing pyplot
matplotlib.use("Agg")

import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator
import pandas as pd

#Determening if it's used for RV/LV or NORMAL/IMPAIRED
TASK_CONFIGS = {
    "rvlv": {
        "class_names": ["RV", "LV"],
        "probability_column": "probability_lv",
        "probability_label": "Predicted LV probability",
        "title": "RV/LV classification",
    },
    "function": {
        "class_names": ["Normal", "Impaired"],
        "probability_column": "probability_impaired",
        "probability_label": "Predicted impaired-function probability",
        "title": "Ventricular function classification",
    }
}

def plot_training_curves(history_path, task, title=None):
    task_config = TASK_CONFIGS[task]
    history_path = Path(history_path)
    history = pd.read_csv(history_path)

    required_columns = [
        "epoch",
        "train_loss",
        "val_loss",
        "train_auroc",
        "val_auroc",
        "train_accuracy",
        "val_accuracy",
    ]

    missing = [
        column
        for column in required_columns
        if column not in history.columns
    ]

    if missing:
        raise ValueError(
            f"Missing columns: {missing}."
            "Use a history generated by the updated training script."
        )

    if history.empty:
        raise ValueError("The training history contains no epochs.")

    for column in required_columns:
        history[column] = pd.to_numeric(
            history[column],
            errors="raise",
        )

    history = history.sort_values("epoch")

    fig, axes = plt.subplots(
        1,
        3,
        figsize=(15, 4.5),
        constrained_layout=True,
    )

    figure_title = task_config["title"]

    if title:
        figure_title += f" - {title}"

    fig.suptitle(f"{figure_title}\nSeries-level performance")

    positive_class = task_config["class_names"][1]

    panels = [
        ("loss", "Binary cross_entropy loss"),
        ("auroc", f"AUROC ({positive_class} = positive)"),
        ("accuracy", "Accuracy"),
    ]

    for ax, (metric, ylabel) in zip(axes, panels):
        ax.plot(
            history["epoch"],
            history[f"train_{metric}"],
            label="Training",
            color="tab:blue",
            marker="o",
            markersize=3,
        )

        ax.plot(
            history["epoch"],
            history[f"val_{metric}"],
            label="Validation",
            color="tab:orange",
            marker="o",
            markersize=3,
        )

        ax.set_xlabel("Epoch")
        ax.set_ylabel(ylabel)
        ax.xaxis.set_major_locator(MaxNLocator(integer=True))
        ax.grid(alpha=0.3)

        if metric == "auroc":
            ax.axhline(
                0.5,
                color="gray",
                linestyle="--",
                label="Chance AUROC",
            )

        if metric in ("auroc", "accuracy"):
            ax.set_ylim(0, 1)

        ax.legend()

    #Keep each method's results seperate, save beside the CSV
    try: 
        for extension in ("png", "pdf"):
            output_path = history_path.parent / (
                f"training_curves_{task}.{extension}"
            )

            fig.savefig(output_path, dpi=200)
            print(f"Saved: {output_path}")
    finally:
        plt.close(fig)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Save training and validation curves from a CSV."
    )

    parser.add_argument(
        "history",
        help="Path to training_history.csv",
    )

    parser.add_argument(
        "--task",
        choices=["rvlv", "function"],
        required=True,
    )

    parser.add_argument(
        "--title",
        default=None,
        help="Optional description, such as Linear probing",
    )

    args = parser.parse_args()

    plot_training_curves(args.history, args.task, args.title)

